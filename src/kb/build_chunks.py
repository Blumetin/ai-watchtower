def prep_chunks() -> list[tuple]:
    text = open(PREP_DOC, encoding="utf-8").read()
    zh = text[text.index("## 一、中文"):text.index("### 急救知識")]
    out, cur, lines = [], None, []

    pending = []
    for raw in zh.splitlines():
        line = raw.strip()
        m = re.match(r"\*\*(.+?)\*\*", line)
        if m and m.group(1) in PREP_MAP:
            if cur and lines:
                pending.append((cur, lines))
            cur, lines = m.group(1), []
        elif line.startswith("- ") and cur:
            lines.append(line[2:])
        elif line.startswith("資料來源：") and cur:
            pending.append((cur, lines))
            for name, ls in pending:
                topic, scen, src, url = PREP_MAP[name]
                out.append((src, url, topic, scen, "\n".join(ls) + "\n" + line))
            pending, cur, lines = [], None, []
    missing = set(PREP_MAP) - {k for k in PREP_MAP if any(PREP_MAP[k][:2] == (t, s) for _, _, t, s, _ in out)}
    assert not missing, f"防災準備頁找不到這些小標：{missing}"
    return out


